const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, ja };

export const languageOptions: Array<{ id: Language; labelKey: TranslationKey }> = [
  { id: "en", labelKey: "language.en" },
  { id: "ja", labelKey: "language.ja" },
];

export function createTranslator(language: Language): Translator {
  return (key, values) => {
    const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
  };
}

export function detectInitialLanguage(tags?: readonly string[]): Language {
  const languageTags =
    tags ??
    (typeof navigator === "undefined"
      ? []
      : navigator.languages && navigator.languages.length > 0
        ? navigator.languages
        : [navigator.language]);

  for (const tag of languageTags) {
    const language = normalizeLanguageTag(tag);
    if (language) return language;
  }
  return "en";
}

export function normalizeLanguageTag(tag: string): Language | undefined {
  const normalized = tag.toLowerCase();
  if (normalized === "ja" || normalized.startsWith("ja-")) return "ja";
  if (normalized === "en" || normalized.startsWith("en-")) return "en";
  return undefined;
}
